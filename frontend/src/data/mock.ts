export type { CryptoFinding, CBOMReport };

// Derived stats for charts
export function getAlgorithmStats(findings: CryptoFinding[]) {
  const counts: Record<string, { count: number; quantum: boolean }> = {};
  for (const f of findings) {
    const base = f.algorithm.split("-")[0];
    if (!counts[base]) counts[base] = { count: 0, quantum: f.quantum_vulnerable };
    counts[base].count++;
    if (f.quantum_vulnerable) counts[base].quantum = true;
  }
  return Object.entries(counts)
    .map(([name, { count, quantum }]) => ({ name, count, quantumVulnerable: quantum }))
    .sort((a, b) => b.count - a.count);
}

export function getRiskDistribution(findings: CryptoFinding[]) {
  const counts: Record<string, number> = { Critical: 0, High: 0, Medium: 0, Low: 0, Safe: 0 };
  for (const f of findings) counts[f.risk_level]++;
  const colors: Record<string, string> = {
    Critical: "#EF4444",
    High: "#F97316",
    Medium: "#F59E0B",
    Low: "#3B82F6",
    Safe: "#10B981",
  };
  return Object.entries(counts)
    .filter(([, v]) => v > 0)
    .map(([name, value]) => ({ name, value, color: colors[name] }));
}
